type I18nValue = { locale: Locale; setLocale: (locale: Locale) => void; t: (key: string, vars?: Record<string, string | number>, fallback?: string) => string };
const I18nContext = createContext<I18nValue>({ locale: "en", setLocale: () => undefined, t: (key, _vars, fallback) => fallback ?? key });
const STORAGE_KEY = "momentum-one-language";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "ro" || saved === "es") setLocaleState(saved);
  }, []);
  const setLocale = (next: Locale) => {
    setLocaleState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  };
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, vars, fallback) => {
      let value = translations[locale][key] ?? fallback ?? key;
      for (const [name, replacement] of Object.entries(vars ?? {})) value = value.replaceAll(`{${name}}`, String(replacement));
      return value;
    },
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() { return useContext(I18nContext); }
